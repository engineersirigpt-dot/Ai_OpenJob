/**
 * Build instructions for the AI meeting participant.
 *
 * The AI listens to the meeting in real-time, has access to uploaded
 * meeting documents, and only speaks when explicitly asked (comment / question).
 */

/**
 * Meeting mode. พรชัย is the assistant in ALL of them (same persona, same
 * models, same memory) — the mode only changes what the meeting is about,
 * where the documents come from, and what to focus on.
 *   "default"  = ประชุมงาน OK  (WI + CAR history pulled from REPORT2)
 *   "pornchai" = พรชัยผู้ช่วยประชุม (general advisory, uploaded documents)
 *   "car"      = สอบสวน CAR (corrective-action investigation hearing)
 */
export type AssistantMode = "default" | "pornchai" | "car";

interface BuildMeetingInstructionsInput {
  meetingTitle?: string;
  documents: { name: string; content: string }[];
  participants?: string[];
  /** lite = include only the job list (no content) — used as a fallback when
   *  the full payload is too large for session creation. */
  lite?: boolean;
  mode?: AssistantMode;
  /** พรชัย long-term memory block ("- fact" per line), injected each session. */
  memory?: string;
}

export function buildMeetingInstructions({
  meetingTitle,
  documents,
  participants,
  lite = false,
  mode = "default",
  memory = "",
}: BuildMeetingInstructionsInput): string {
  let docsBlock: string;
  if (!documents.length) {
    docsBlock = "(ไม่มีเอกสารประกอบการประชุม)";
  } else if (lite) {
    // Names only — content is injected on demand when summarizing CAR/comment
    docsBlock =
      "เอกสารที่โหลดไว้ (เนื้อหาเต็มจะถูกส่งให้เมื่อกดสรุป CAR/ข้อเสนอแนะ):\n" +
      documents.map((d, i) => `${i + 1}. ${d.name}`).join("\n");
  } else {
    // Cap per-document and total size so the instructions payload stays small
    // enough for session creation.
    const PER_DOC = 16000;
    const TOTAL_BUDGET = 36000;
    let used = 0;
    const blocks = documents.map((d, i) => {
      if (used >= TOTAL_BUDGET) {
        return `[เอกสาร ${i + 1}: ${d.name}] (ไม่ได้แสดงเนื้อหา — โหลดหลายไฟล์เกินไป)`;
      }
      const limit = Math.min(PER_DOC, TOTAL_BUDGET - used);
      const slice = d.content.slice(0, limit);
      used += slice.length;
      const note = slice.length < d.content.length ? "\n…(ตัดบางส่วนเพราะยาวเกิน)" : "";
      return `[เอกสาร ${i + 1}: ${d.name}]\n${slice}${note}`;
    });
    docsBlock = blocks.join("\n\n---\n\n");
  }

  const participantsBlock = participants?.length
    ? `ผู้เข้าร่วมประชุม: ${participants.join(", ")}`
    : "";

  // พรชัย is the assistant in every mode — one persona, one prompt core.
  return buildPornchaiInstructions(meetingTitle, docsBlock, participantsBlock, memory, mode);
}

/** Per-mode block: what this meeting is, which documents, what to focus on. */
function meetingModeBlock(mode: AssistantMode): string {
  if (mode === "default") {
    return `## 0. โหมดประชุมนี้: "ประชุมงาน OK" — ตรวจความพร้อมงานพิมพ์ก่อนผลิต
- เอกสารประกอบคือ WI (ใบสั่งงาน) พร้อมประวัติ CAR ของลูกค้าที่ท้าย WI และส่วน "CAR/PAR ของงานนี้จากระบบ" ที่ระบบดึงมาต่อท้ายให้ ตามเลขที่งาน (Job ID เช่น J82600396)
- PAR (Preventive Action Request) คือใบขอให้ป้องกันที่ออกเมื่อเห็นความเสี่ยงก่อนเกิดความเสียหาย ต่างจาก CAR ที่ออกหลังเกิดปัญหา ถ้างานที่กำลังคุยมี PAR ให้เตือนที่ประชุมเองทันทีเมื่อถูกสั่งให้พูด โดยบอกเลขที่ เรื่อง และว่าแนวทางป้องกันตอบแล้วหรือยัง
- โฟกัสของโหมดนี้: ความพร้อมของงาน — สเปค จำนวน กำหนดส่ง ลูกค้า AE ขั้นตอนผลิต และ "ปัญหาที่เคยเกิดกับลูกค้ารายนี้ (CAR)" เพื่อเตือนไม่ให้เกิดซ้ำ
- เวลาอ้างข้อมูลงาน ให้ระบุ Job ID แล้วอ่านค่าจากเอกสารตรงๆ ทีละฟิลด์ (Job ID, ชื่องาน, ลูกค้า, AE, จำนวน, วันที่, ตาราง CAR)
- เอกสาร WI แปลงมาจาก PDF อาจมีช่องว่างหรือวรรณยุกต์เพี้ยน ให้ตีความตามบริบทได้ แต่ห้ามเดาค่าตัวเลขหรือชื่อ`;
  }
  if (mode === "car") {
    return `## 0. โหมดประชุมนี้: "สอบสวน CAR" (Corrective Action Request)
- นี่คือการประชุมสอบสวนงานเสีย/งานขาดยอด ตามตารางสอบสวน CAR ซึ่งมีคอลัมน์: ลำดับ, เลขที่ CAR, ชื่องาน, เลขที่งาน, วันที่ออก CAR, รายละเอียดปัญหา, สถานะ, มูลค่า, ผู้ออก CAR, ฝ่ายที่ออก CAR, หน่วยที่ได้รับ CAR, ผู้ตอบ CAR, ผลการตอบ (ยอมรับ/ไม่ยอมรับ), หมายเหตุ
- บทบาทของพรชัยในโหมดนี้คือ "ผู้ช่วยกรรมการสอบสวน" — ฟังคำชี้แจงของหน่วยที่ได้รับ CAR แล้วช่วยตรวจว่าคำตอบครบพอจะปิดเคสหรือยัง
- เมื่อถูกสั่งให้พูด ให้ตรวจ 5 ประเด็นนี้เป็นหลัก: (1) สาเหตุรากจริง ไม่ใช่อาการ (2) ขอบเขตความเสียหาย จำนวน/มูลค่า (3) การแก้ไขเฉพาะหน้า (4) การป้องกันไม่ให้เกิดซ้ำ — ใครทำ เมื่อไหร่ (5) หลักฐานหรือตัวชี้วัดที่จะยืนยันว่าแก้ได้จริง
- ถ้าคำตอบยังขาดประเด็นไหน ให้ตั้งคำถามเจาะต่อแบบกรรมการสอบ เช่น ตรวจที่จุดไหน ใช้เครื่องมืออะไร ค่าเท่าไรถือว่าผ่าน ถ้าไม่ผ่านจะทำอย่างไร
- ห้ามตัดสินแทนกรรมการว่า "ยอมรับ/ไม่ยอมรับ" — เสนอได้แค่ว่าข้อมูลพอหรือยัง และต้องขออะไรเพิ่ม โดยอ้างคำพูดจริงในที่ประชุมและข้อมูลในตาราง CAR เป็นหลักฐานทุกครั้ง
- ห้ามแต่งเลขที่ CAR ชื่อผู้ออก/ผู้ตอบ CAR มูลค่า หรือผลการตอบ ถ้าไม่มีในเอกสาร`;
  }
  return `## 0. โหมดประชุมนี้: "พรชัยผู้ช่วยประชุม" — ที่ปรึกษาทั่วไป
- เป็นการประชุมหรือปรึกษากับเฮียได้ทุกเรื่อง ไม่จำกัดว่าต้องเป็นงานพิมพ์
- เอกสารประกอบมาจากการอัปโหลดเอง (PDF/DOCX/XLSX/TXT) หรือแชทเก่าที่ดึงมา — ยึดเนื้อหาที่แนบจริงเท่านั้น
- โฟกัส: ช่วยคิด วิเคราะห์ เสนอทางเลือกพร้อมข้อดีข้อเสีย ชี้ความเสี่ยงที่อาจถูกมองข้าม และสรุปให้เฮียตัดสินใจได้`;
}

/** Kept for reference — the old generic (non-พรชัย) meeting prompt. */
